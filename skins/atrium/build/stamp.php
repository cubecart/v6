<?php
/**
 * Writes templates/element.css.version.php — a content hash of the built CSS,
 * used as the ?v= cache-buster in element.css.php.
 *
 * WHY: {combine} normally provides cache-busting by writing mtime-stamped
 * filenames (function.combine.php: date('_YmdHis.', $last_mtime)). Atrium serves
 * its stylesheet with a plain <link> instead — the file is already minified by
 * Lightning CSS, and {combine} would re-minify it and rewrite url()/'../images/'
 * for no benefit (see templates/element.css.php) — so it must supply its own
 * cache-buster.
 *
 * Do NOT use {$SKIN_VERSION} — core does not assign it. gui.class.php assigns
 * SKIN_FOLDER (:1959) and SKIN_SUBSET (:1993) only.
 */
$root = dirname(__DIR__);
$out  = $root . '/templates/element.css.version.php';
$hash = 'dev';

// The JS bundle is served with the same ?v= as the CSS, so it must be part of
// the hash — otherwise a JS-only fix ships behind a stale cache-buster and
// returning browsers keep the broken bundle indefinitely.
foreach (['/css/tailwind.css', '/css/custom.css', '/js/vendor/0.atrium.components.js'] as $f) {
    if (is_file($root . $f)) {
        $hash = substr(hash('sha256', $hash . hash_file('sha256', $root . $f)), 0, 10);
    }
}

// scope='global' is REQUIRED. Smarty {assign} inside an {include} is local to
// the included template by default, so without it $CSS_VERSION is empty in
// element.css.php and element.js_foot.php and every asset URL ends in "?v=".
file_put_contents($out, "{* GENERATED by build/stamp.php — do not edit *}\n"
    . "{assign var=CSS_VERSION value='" . $hash . "' scope='global'}\n");

echo "element.css.version.php -> {$hash}\n";
