#!/usr/bin/env bash
# Concatenate js/src/*.js into the single shipped bundle.
#
# Output goes to js/vendor/ (NOT js/), deliberately:
#   - js/*.js is auto-globbed into $JS_SCRIPTS (classes/gui.class.php:192) and
#     rendered through {combine}, which runs JSMin over it. JSMin throws a PHP
#     fatal on an apostrophe inside a template literal and silently corrupts
#     other backtick strings.
#   - js/vendor/ is NOT globbed, so this bundle is loaded by a hand-written
#     <script> tag in element.js_foot.php and never touches JSMin.
# The {combine} call for $JS_SCRIPTS stays in element.js_foot.php regardless,
# because plugins drop files into js/ and expect it.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=js/vendor/0.atrium.components.js
mkdir -p js/vendor

{
  echo "/* Atrium skin bundle — GENERATED by build/bundle-js.sh. Do not edit."
  echo "   Sources: js/src/*.js (concatenated in filename order). */"
  for f in js/src/*.js; do
    echo ""
    echo "/* ---- $f ---- */"
    cat "$f"
  done
} > "$OUT"

# Fail the build rather than ship a syntax error to every storefront.
if command -v node >/dev/null 2>&1; then
  node --check "$OUT"
  echo "syntax OK"
fi

# Guard the JSMin rule at build time, not in code review.
# Strips comments first — backticks in prose are fine, only code matters.
python3 "$(dirname "$0")/check-no-template-literals.py"

# Restamp: the bundle is part of the cache-buster hash (see build/stamp.php).
php "$(dirname "$0")/stamp.php"

echo "bundled $OUT ($(wc -c < "$OUT") bytes)"
